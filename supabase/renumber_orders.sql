alter table orders alter column id set generated by default;

create function renumber_orders() returns trigger language plpgsql security definer set search_path = public as $$
begin
  lock table orders in share row exclusive mode;
  update orders o set id = -r.n
  from (select id, row_number() over (order by id) as n from orders) r
  where o.id = r.id and o.id <> r.n;
  update orders set id = -id where id < 0;
  perform setval(pg_get_serial_sequence('orders', 'id'), coalesce((select max(id) from orders), 0) + 1, false);
  return null;
end $$;
revoke execute on function renumber_orders() from public, anon, authenticated;
create trigger renumber after delete on orders for each statement execute function renumber_orders();
